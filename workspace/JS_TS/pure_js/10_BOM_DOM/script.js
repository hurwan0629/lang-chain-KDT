/*
BOM

Browser Object Mode
자바스크립트가 브라우저 자체를 제어하고 정보를 얻기 위해 사용하는 객체 모델 

API(Application Programming Interface)
서로 다른 프로그램이나 시스템이 데이터를 주고받고 기능을 사용할 수
있도록 연결해주는 중간 통로

1. window 객체
자바스크립트에서 브라우저 창을 대표하는 최상위 객체로, 전역 범위에서
정의된 변수나 함수, 타이머, 팝업, 브라우저 정보 등 대부분의 기능을
포함하고 있음

- HTML 페이지를 로드하면 브라우저는 자동으로 window 객체를 생성하며,
자바스크립트 코드에서 명시적으로 window를 쓰지 않아도 사용할 수 있음

3. history 객체
- 브라우저의 방문 기록을 제어할 수 있는 객체로, 사용자가 이전에 방문했던
페이지로 이동하거나 앞으로 다시 이동할 수 있는 기능을 제공

4. navigator 객체
- 브라우저에 대한 정보를 제공하는 객체로, 사용자의 브라우저 종류, 버전,
운영체제, 언어 설정, 온라인 여부 등 다양한 환경 정보를 확인할 수 있도록
해줌
- geolocation: 사용자의 위치 정보를 가져오기 위한 API로, GPS, WIFI,
IP 주소 등을 이용해 현재 위치를 알아냄. 사용자의 명시적인 동의가 있어야
작동함

DOM 작동 원리
1. 브라우저가 HTML 파일을 읽음
2. HTML 태그를 하나하나 분석하여 트리 구조의 객체를 생성
3. 각 태그는 노드라는 객체가 됨
4. 자바스크립트는 DOM 객체를 통해 화면을 제어

Document 객체
- 웹 페이지 전체를 표현하는 최상위 DOM 객체로, HTML 문서에 직접
접근하고 조작할 수 있는 핵심 객체
- 브라우저가 HTML 파일을 로드하면 자동으로 document 객체가 생성되며, 이
객체를 통해 웹 페이지의 요소들을 선택하거나 생성, 수정, 삭제할 수 있음
*/